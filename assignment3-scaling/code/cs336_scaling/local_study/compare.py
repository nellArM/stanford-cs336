"""Compare the predicted final loss with the actual target run and write the result for the report.

Usage:  uv run --extra study python -m cs336_scaling.local_study.compare
"""

from __future__ import annotations

import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from cs336_scaling.local_study import grid as G
from cs336_scaling.local_study.fit import FIG_DIR, GEN_DIR, PREDICTION_PATH, load_runs, parametric_loss


def main() -> None:
    prediction = json.loads(PREDICTION_PATH.read_text())
    log_path = G.RUN_DIR / "target.jsonl"
    records = [json.loads(line) for line in log_path.read_text().splitlines()] if log_path.exists() else []
    evals = [r for r in records if r["type"] == "eval"]
    final = next((r for r in records if r["type"] == "final"), None)
    if not evals:
        raise SystemExit("the target run has not produced any evaluation yet")

    predicted = prediction["predicted_final_loss"]
    tokens = np.array([e["tokens"] for e in evals], dtype=float)
    losses = np.array([e["val_loss"] for e in evals])

    fig, ax = plt.subplots(figsize=(6.4, 4.2))
    ax.plot(tokens, losses, marker="o", ms=3, color="#1f4e79", label="target run (validation, 2^18 tokens)")
    ax.axhline(predicted, color="#c0392b", ls="--", label=f"predicted final loss {predicted:.3f}")
    if prediction.get("envelope_predicted_loss"):
        ax.axhline(prediction["envelope_predicted_loss"], color="#e69f00", ls=":",
                   label=f"envelope extrapolation {prediction['envelope_predicted_loss']:.3f}")  # fmt: skip
    best_grid = min(r["final_val_loss"] for r in load_runs())
    ax.axhline(best_grid, color="gray", ls="-.", lw=1, label=f"best scaling run {best_grid:.3f}")
    ax.set_xscale("log")
    ax.set_xlabel("Training tokens")
    ax.set_ylabel("Validation loss")
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(FIG_DIR / "study_target.png", dpi=200)
    plt.close(fig)

    lines = ["// Generated by cs336_scaling/local_study/compare.py -- do not edit by hand.", ""]
    if final is None or final["status"] != "completed":
        done = evals[-1]["tokens"] / prediction["tokens"]
        status = final["status"] if final else "still running"
        lines.append(
            f"*The target run is not complete ({status}; {done * 100:.0f}% of its tokens).* "
            f"Latest validation loss: {losses[-1]:.4f} against a prediction of {predicted:.3f} for the finished run."
        )
    else:
        actual = final["final_val_loss"]
        error = predicted - actual
        partial = parametric_loss(prediction["parametric_fit"], prediction["n_params"], prediction["tokens"])
        lines += [
            "#table(columns: 2, align: (left, right),",
            f"  [Target configuration], [{prediction['model']}, {prediction['tokens'] / 1e6:.0f}M tokens, batch {prediction['batch_size']}, LR {prediction['lr']:g}],",
            f"  [Predicted final validation loss (parametric fit)], [{partial:.4f}],",
            f"  [*Actual final validation loss* (2#super[18] tokens)], [*{actual:.4f}*],",
            f"  [Prediction error (predicted - actual)], [{error:+.4f} nats ({error / actual * 100:+.1f}%)],",
        ]
        if prediction.get("envelope_predicted_loss"):
            env = prediction["envelope_predicted_loss"]
            lines.append(f"  [Envelope extrapolation and its error], [{env:.4f} ({env - actual:+.4f})],")
        lines += [
            f"  [Actual loss on the larger 2#super[21]-token validation set], [{final['final_val_loss_2M_tokens']:.4f}],",
            f"  [Best loss among the scaling runs], [{best_grid:.4f}],",
            f"  [Training time], [{final['train_seconds'] / 3600:.2f} A6000-hours ({final['flops_per_second']:.2e} FLOP/s)],",
            ")",
        ]
    lines += ["", '#figure(image("../figures/study_target.png", width: 75%), caption: [Target run against the predictions made before it was started.])']
    (GEN_DIR / "study_target.typ").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
